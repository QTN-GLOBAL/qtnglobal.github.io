/* =========================
   CORE FUNCTION
========================= */

let currentLang =
    localStorage.getItem("language") || "vi";


function t(key) {

    return translations[currentLang]?.[key]
        || translations.vi?.[key]
        || key;
}


/* =========================
   APPLY LANGUAGE TO PAGE
========================= */

function applyLanguage(lang) {

    const dict = translations[lang];

    if (!dict) return;

    document.documentElement.lang = lang;


    /* =========================
       TEXT CONTENT
    ========================= */

    document.querySelectorAll("[data-i18n]").forEach(el => {

        const key = el.dataset.i18n;

        if (dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }

    });


    /* =========================
       PLACEHOLDER
    ========================= */

    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {

        const key = el.dataset.i18nPlaceholder;

        if (dict[key] !== undefined) {
            el.placeholder = dict[key];
        }

    });

}


/* =========================
   REFRESH DYNAMIC UI
========================= */

function refreshUIAfterLanguageChange() {

    /*
       Không thay đổi dữ liệu products.js.
       Không tạo lại product object.
       Chỉ yêu cầu các hàm hiện tại của website
       render lại giao diện theo ngôn ngữ.
    */

    if (typeof renderHomeByBrand === "function") {
        renderHomeByBrand();
    }


    if (typeof renderAboutContent === "function") {
        renderAboutContent();
    }


    if (typeof renderProducts === "function") {

        if (typeof getProducts === "function") {

            const products =
                window.currentProducts || getProducts();

            renderProducts(products);

        } else if (window.currentProducts) {

            renderProducts(window.currentProducts);

        }

    }


    if (typeof renderProductList === "function") {

        if (
            window.lastProducts &&
            window.lastTitle
        ) {

            renderProductList(
                window.lastProducts,
                window.lastTitle
            );

        }

    }


    if (typeof renderProductDetail === "function") {
        renderProductDetail();
    }


    /* =========================
       RESTART SLIDERS
    ========================= */

    setTimeout(() => {

        if (typeof initHeroSlider === "function") {
            initHeroSlider();
        }

        if (typeof initBrandSliders === "function") {
            initBrandSliders();
        }

    }, 0);

}


/* =========================
   SET LANGUAGE
========================= */

function setLanguage(lang) {

    if (!translations[lang]) {
        lang = "vi";
    }

    currentLang = lang;

    localStorage.setItem(
        "language",
        lang
    );

    applyLanguage(lang);

    refreshUIAfterLanguageChange();

}


/* =========================
INIT LANGUAGE SELECT
========================= */

document.addEventListener("DOMContentLoaded", () => {
const select = document.getElementById("languageSelect");
const savedLang = localStorage.getItem("language") || "vi";
const lang = translations[savedLang] ? savedLang : "vi";


setLanguage(lang);

if (select) {
    select.value = lang;
}


});

document.addEventListener("change", (event) => {
if (event.target && event.target.id === "languageSelect") {
setLanguage(event.target.value);
}
});
